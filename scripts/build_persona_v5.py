def main():
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

    if not os.path.exists(SRC):
        print("中止：找不到 v4 备份 %s" % SRC)
        return 1

    with io.open(SRC, encoding="utf-8") as f:
        text = f.read()

    src_sha = hashlib.sha256(text.encode("utf-8")).hexdigest().upper()
    print("源文件: %s" % os.path.basename(SRC))
    print("源字节: %d  源 sha256: %s" % (len(text.encode("utf-8")), src_sha))
    if src_sha != SRC_SHA_EXPECT:
        print("中止：源文件不是 v4（期望 %s）。" % SRC_SHA_EXPECT)
        return 1
    print("源文件校验: 是 v4 ✓")
    print("替换项数: %d" % len(EDITS))
    print("-" * 72)

    failures = []
    out = text
    for tag, old, new in EDITS:
        n = out.count(old)
        print("[%s] %-24s 命中=%d" % ("OK " if n == 1 else "FAIL", tag, n))
        if n != 1:
            failures.append((tag, n))
            continue
        out = out.replace(old, new, 1)

    print("-" * 72)
    if failures:
        print("中止：以下替换点没有恰好命中 1 次，未写入任何文件：")
        for tag, n in failures:
            print("  - %s (命中 %d 次)" % (tag, n))
        return 2

    leftover = [s for s in MUST_BE_GONE if s in out]
    if leftover:
        print("中止：旧说法仍残留：%s" % leftover)
        return 3

    missing = [s for s in MUST_BE_PRESENT if s not in out]
    if missing:
        print("中止：新规则没写进去：%s" % missing)
        return 4

    # 「同桌」出现次数自检：规则 1 处 + 示范 3 句 + 引用若干
    print("「同桌」出现次数: %d" % out.count("同桌"))
    # 「只有一处定义」的机器断言：频率数字只能出现在
    #   ① 版本头的变更说明
    #   ② 第四节「老爹」那一条（v4 原有的，未改）
    #   ③ 第四节「同桌」那一条（本次新增）
    # —— ②③ 同属第四节，所以"规则定义"确实只有一处（第四节）。
    # 出现在第 4 个地方，就说明规则被写散了。
    n_freq = out.count("十轮之内最多")
    print("「十轮之内最多」出现次数: %d（应为 3：版本头 + 第四节老爹 + 第四节同桌）" % n_freq)
    if n_freq != 3:
        print("中止：频率规则出现在 %d 处，规则被写散了。" % n_freq)
        return 7
    # 「二选一、不叠加」是本次改动的核心措辞：版本头 + 三·五提示 + 第四节定义
    #   + 第十节引用，共 4 处；多一处就说明规则被写散了
    n_either = out.count("二选一、不叠加")
    print("「二选一、不叠加」出现次数: %d（应为 4：版本头 + 三·五 + 第四节 + 第十节）" % n_either)
    if n_either != 4:
        print("中止：「二选一、不叠加」出现 %d 处，与预期 4 处不符。" % n_either)
        return 8

    data = out.encode("utf-8")
    if data.startswith(b"\xef\xbb\xbf"):
        print("中止：输出带 BOM。")
        return 5
    if b"\r" in data:
        print("中止：输出含 CR（要求 LF）。")
        return 6

    with open(DST, "wb") as f:
        f.write(data)

    print("已写入: %s" % os.path.basename(DST))
    print("新字节: %d" % len(data))
    print("新 sha256: %s" % hashlib.sha256(data).hexdigest().upper())
    print("BOM: 无  行尾: LF")
    return 0


if __name__ == "__main__":
    sys.exit(main())
