def main():
    with io.open(SRC, encoding="utf-8") as f:
        text = f.read()

    src_sha = hashlib.sha256(text.encode("utf-8")).hexdigest().upper()
    print("源文件: %s" % SRC)
    print("源字节: %d  源 sha256: %s" % (len(text.encode("utf-8")), src_sha))
    print("替换项数: %d" % len(EDITS))
    print("-" * 72)

    failures = []
    out = text
    for tag, old, new in EDITS:
        n = out.count(old)
        status = "OK " if n == 1 else "FAIL"
        print("[%s] %-28s 命中=%d" % (status, tag, n))
        if n != 1:
            failures.append((tag, n))
            continue
        out = out.replace(old, new, 1)

    print("-" * 72)
    if failures:
        print("中止：以下替换点没有恰好命中 1 次，未写入任何文件：")
        for tag, n in failures:
            print("  - %s (命中 %d 次)" % (tag, n))
        return 2

    # 残留检查：不得再有「把对话者称站长」的规则性表述
    banned_rule_fragments = [
        "默认叫「**站长**」",
        "【对站长】",
        "需要点明身份、或话里带点调侃时",
    ]
    leftover = [b for b in banned_rule_fragments if b in out]
    if leftover:
        print("中止：仍残留称呼规则片段：%s" % leftover)
        return 3

    data = out.encode("utf-8")
    if data.startswith(b"\xef\xbb\xbf"):
        print("中止：输出带 BOM。")
        return 4

    with open(DST, "wb") as f:
        f.write(data)

    print("已写入: %s" % DST)
    print("新字节: %d" % len(data))
    print("新 sha256: %s" % hashlib.sha256(data).hexdigest().upper())
    print("BOM: 无")
    print("剩余「站长」出现次数: %d" % out.count("站长"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
